"""CPU-visible task geometry for gfx1250 DFlash2 TP4 kernels."""

from sgl_amd_mono.muse_spark.gfx1250.draft_config import (
    COEF_ROWS,
    GATE_UP_ROWS,
    HIDDEN,
    LOCAL_INTERMEDIATE,
    MAX_TOKENS,
    QKV_ROWS,
    Q_K,
    RESIDENT_BLOCKS,
)

THREADS = 256
WAVE_SIZE = 32
WAVES = THREADS // WAVE_SIZE
ROWS = 16

HIDDEN_K_PARTS = 16
HIDDEN_K_PART = HIDDEN // HIDDEN_K_PARTS

COEF_ROWS_PER_GROUP = 128
COEF_GROUPS = COEF_ROWS // COEF_ROWS_PER_GROUP
COEF_TASKS = COEF_GROUPS * HIDDEN_K_PARTS

GATE_UP_ROWS_PER_GROUP = 448
GATE_UP_GROUPS = GATE_UP_ROWS // GATE_UP_ROWS_PER_GROUP
GATE_UP_TASKS = GATE_UP_GROUPS * HIDDEN_K_PARTS

DOWN_K_PART = 512
DOWN_K_PARTS = LOCAL_INTERMEDIATE // DOWN_K_PART
DOWN_ROWS_PER_GROUP = 256
DOWN_GROUPS = HIDDEN // DOWN_ROWS_PER_GROUP
DOWN_TASKS = DOWN_K_PARTS * DOWN_GROUPS

QKV_ROWS_PER_GROUP = 160
QKV_GROUPS = QKV_ROWS // QKV_ROWS_PER_GROUP
QKV_TASKS = QKV_GROUPS * HIDDEN_K_PARTS

O_K_PARTS = Q_K // HIDDEN_K_PART
O_ROWS_PER_GROUP = 32
O_GROUPS = HIDDEN // O_ROWS_PER_GROUP
O_TASKS = O_GROUPS

ATTENTION_TASKS = MAX_TOKENS * (Q_K // 128)


def rounds(tasks: int) -> int:
    return (tasks + RESIDENT_BLOCKS - 1) // RESIDENT_BLOCKS


def tasks_for_block(tasks: int, block_id: int) -> tuple[int, ...]:
    if not 0 <= block_id < RESIDENT_BLOCKS:
        raise ValueError(f"block id {block_id}, want [0, {RESIDENT_BLOCKS})")
    return tuple(range(block_id, tasks, RESIDENT_BLOCKS))


assert HIDDEN_K_PARTS * HIDDEN_K_PART == HIDDEN
assert COEF_GROUPS * COEF_ROWS_PER_GROUP == COEF_ROWS
assert GATE_UP_GROUPS * GATE_UP_ROWS_PER_GROUP == GATE_UP_ROWS
assert DOWN_K_PARTS * DOWN_K_PART == LOCAL_INTERMEDIATE
assert DOWN_GROUPS * DOWN_ROWS_PER_GROUP == HIDDEN
assert QKV_GROUPS * QKV_ROWS_PER_GROUP == QKV_ROWS
assert O_K_PARTS * HIDDEN_K_PART == Q_K
assert O_GROUPS * O_ROWS_PER_GROUP == HIDDEN

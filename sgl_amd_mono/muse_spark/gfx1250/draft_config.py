LOCAL_KV_HEADS = TOTAL_KV_HEADS // TP
LOCAL_INTERMEDIATE = INTERMEDIATE // TP
Q_K = LOCAL_Q_HEADS * HEAD_DIM
KV_K = LOCAL_KV_HEADS * HEAD_DIM
QKV_ROWS = Q_K + 2 * KV_K
GATE_UP_ROWS = 2 * LOCAL_INTERMEDIATE

